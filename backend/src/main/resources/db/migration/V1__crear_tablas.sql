CREATE TABLE tbla_estudiante (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    apellido VARCHAR(120) NOT NULL,
    cedula VARCHAR(20) NOT NULL,
    programa VARCHAR(120) NOT NULL,
    CONSTRAINT uq_estudiante_cedula UNIQUE (cedula)
);

CREATE TABLE tbla_materia (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(120) NOT NULL,
    codigo VARCHAR(20) NOT NULL,
    CONSTRAINT uq_materia_codigo UNIQUE (codigo)
);

CREATE TABLE tbla_matricula (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_estudiante BIGINT NOT NULL REFERENCES tbla_estudiante (id),
    id_materia BIGINT NOT NULL REFERENCES tbla_materia (id),
    nota NUMERIC(3, 2) NOT NULL,
    CONSTRAINT uq_matricula_estudiante_materia UNIQUE (id_estudiante, id_materia),
    CONSTRAINT ck_matricula_nota CHECK (nota BETWEEN 0 AND 5)
);
